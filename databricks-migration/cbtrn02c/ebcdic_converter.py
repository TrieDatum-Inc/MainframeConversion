# Zoned decimal sign nibbles (last byte, low nibble)
# In EBCDIC zoned decimal, the sign is in the zone (high nibble) of the last byte
ZONED_POSITIVE_SIGNS = {0xC, 0xA, 0xE, 0xF}  # C, A, E, F = positive
ZONED_NEGATIVE_SIGNS = {0xD, 0xB}             # D, B = negative


def ebcdic_to_ascii(data: bytes) -> str:
    """Convert EBCDIC bytes to ASCII string."""
    result = []
    for byte in data:
        ascii_byte = EBCDIC_TO_ASCII.get(byte, 0x3F)  # 0x3F = '?' for unknown
        result.append(chr(ascii_byte))
    return ''.join(result)


def parse_char_field(data: bytes) -> str:
    """Parse a character field (PIC X) from EBCDIC."""
    return ebcdic_to_ascii(data).strip()


def parse_zoned_decimal(data: bytes, decimals: int = 0) -> Decimal:
    """
    Parse an unsigned zoned decimal field (PIC 9).
    Each byte represents one digit in EBCDIC (F0-F9 = 0-9).
    """
    digits = []
    for byte in data:
        # Extract the numeric digit (low nibble in EBCDIC)
        digit = byte & 0x0F
        if digit > 9:
            digit = 0  # Handle invalid data
        digits.append(str(digit))
    
    value_str = ''.join(digits)
    if decimals > 0:
        # Insert decimal point
        int_part = value_str[:-decimals] or '0'
        dec_part = value_str[-decimals:]
        value_str = f"{int_part}.{dec_part}"
    
    return Decimal(value_str)


def parse_signed_zoned_decimal(data: bytes, decimals: int = 0) -> Decimal:
    """
    Parse a signed zoned decimal field (PIC S9).
    The sign is encoded in the zone (high nibble) of the last byte.
    """
    if not data:
        return Decimal(0)
    
    digits = []
    is_negative = False
    
    for i, byte in enumerate(data):
        digit = byte & 0x0F
        if digit > 9:
            digit = 0
        digits.append(str(digit))
        
        # Check sign in last byte
        if i == len(data) - 1:
            zone = (byte >> 4) & 0x0F
            is_negative = zone in ZONED_NEGATIVE_SIGNS
    
    value_str = ''.join(digits)
    if decimals > 0:
        int_part = value_str[:-decimals] or '0'
        dec_part = value_str[-decimals:]
        value_str = f"{int_part}.{dec_part}"
    
    value = Decimal(value_str)
    return -value if is_negative else value


def parse_packed_decimal(data: bytes, decimals: int = 0) -> Decimal:
    """
    Parse a packed decimal / COMP-3 field.
    Each byte contains two digits (except last byte which has digit + sign).
    """
    digits = []
    is_negative = False
    
    for i, byte in enumerate(data):
        high_nibble = (byte >> 4) & 0x0F
        low_nibble = byte & 0x0F
        
        if i == len(data) - 1:
            # Last byte: high nibble is digit, low nibble is sign
            if high_nibble <= 9:
                digits.append(str(high_nibble))
            is_negative = low_nibble in {0xD, 0xB}
        else:
            # Other bytes: both nibbles are digits
            if high_nibble <= 9:
                digits.append(str(high_nibble))
            if low_nibble <= 9:
                digits.append(str(low_nibble))
    
    value_str = ''.join(digits) or '0'
    if decimals > 0 and len(value_str) > decimals:
        int_part = value_str[:-decimals]
        dec_part = value_str[-decimals:]
        value_str = f"{int_part}.{dec_part}"
    elif decimals > 0:
        value_str = f"0.{value_str.zfill(decimals)}"
    
    value = Decimal(value_str)
    return -value if is_negative else value


def parse_record(data: bytes, layout: List[Tuple]) -> Dict[str, Any]:
    """
    Parse a complete record based on the field layout.
    
    Args:
        data: Raw EBCDIC bytes
        layout: List of (field_name, start_pos, length, field_type, decimals)
    
    Returns:
        Dictionary with parsed field values
    """
    result = {}
    
    for field_name, start_pos, length, field_type, decimals in layout:
        field_data = data[start_pos:start_pos + length]
        
        if field_type == "char":
            result[field_name] = parse_char_field(field_data)
        elif field_type == "zoned":
            result[field_name] = int(parse_zoned_decimal(field_data, decimals))
        elif field_type == "signed_zoned":
            result[field_name] = parse_signed_zoned_decimal(field_data, decimals)
        elif field_type == "packed":
            result[field_name] = parse_packed_decimal(field_data, decimals)
        else:
            result[field_name] = parse_char_field(field_data)
    
    return result


class EBCDICFileReader:
    """
    Reader for fixed-length EBCDIC record files.
    Used to read mainframe data files like DALYTRAN.
    """
    
    def __init__(self, file_path: str, record_length: int, layout: List[Tuple]):
        self.file_path = file_path
        self.record_length = record_length
        self.layout = layout
    
    def read_records(self):
        """Generator that yields parsed records from the file."""
        with open(self.file_path, 'rb') as f:
            while True:
                data = f.read(self.record_length)
                if not data:
                    break
                if len(data) < self.record_length:
                    # Partial record at end of file
                    break
                yield parse_record(data, self.layout)
    
    def to_list(self) -> List[Dict[str, Any]]:
        """Read all records into a list."""
        return list(self.read_records())


# For Spark UDF usage - parse a single record from binary
def parse_dalytran_record(record_bytes: bytes) -> Dict[str, Any]:
    """Parse a DALYTRAN record from EBCDIC bytes."""
    from schema_definitions import DALYTRAN_EBCDIC_LAYOUT
    return parse_record(record_bytes, DALYTRAN_EBCDIC_LAYOUT)
